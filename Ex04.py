#  1 - Converter String para int, e int para string
# float para string e float para int e vise e versa.

print('Conv ersao de string para int ')
numero = input('Digite um número: ')
numero_inteiro = int(numero)
print(numero_inteiro * 2)

print('Conversao de int para string ')
texto = int(input('Digite um número: '))
numero_string = str(texto)
print(numero_string + '!!')

print('Conversao de string para float ')
numero_flutuante = input('Digite um número: ')
numero_para_flutuante = float(numero_flutuante)
print(numero_para_flutuante)

print('Conversao de float para int ')

numero_conversao_float = input('Digite um número de ponto flutuante: ')
numero_conversao = float(numero_conversao_float)
numero_conversao_int = int(numero_conversao)

print(numero_conversao_int)
